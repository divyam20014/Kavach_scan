#!/usr/bin/env python
"""Generate a local demo project with synthetic findings, assets and scan records.

This is a standalone operator tool, not part of the running application (nothing under
`app/` imports it, and it is never wired into any API route or UI action) — it exists so a
new developer or evaluator can see the UI populated without running a real scan or needing
network access at all. It never contacts a target, never runs a scanner, and never writes
anything resembling a real credential: every target is an RFC 2606 reserved "example" domain,
every finding is clearly labelled synthetic, and the "evidence" text is hand-written,
recognizable placeholder content.

Usage (from `backend/`):

    poetry run python scripts/generate_demo_project.py --data-dir /path/to/demo-data

`--data-dir` is required and must not be the operator's real data directory — this script
always creates a **new** project in whatever directory you point it at; run it against a
throwaway directory (or the same one you pass as `VAPT_DATA_DIR` when trying out the UI).
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # make `app` importable

from app.core.settings import RuntimeSettings  # noqa: E402
from app.models.asset import Asset  # noqa: E402
from app.models.common import (  # noqa: E402
    AssetType,
    Confidence,
    ScanModule,
    ScanState,
    ScopeStatus,
    Severity,
    new_id,
)
from app.models.finding import Finding, FindingSource, StandardMapping  # noqa: E402
from app.models.project import (  # noqa: E402
    AuthorizationRecord,
    Project,
    ScanPolicy,
    ScopeDefinition,
)
from app.models.scan import ScanJob  # noqa: E402
from app.storage.errors import StorageError  # noqa: E402
from app.storage.repository import StorageRepository  # noqa: E402

DEMO_HOST = "demo.example.test"  # RFC 2606 reserved — never resolvable, never contacted


def _demo_project(now: datetime) -> Project:
    return Project(
        project_id=new_id("project"),
        name="Demo Assessment (synthetic data — no scan was run)",
        client_name="Example Demo Co.",
        description=(
            "Generated by scripts/generate_demo_project.py for local evaluation only. "
            "Every record here is fabricated; no network request was ever made."
        ),
        authorization=AuthorizationRecord(
            organization="Example Demo Co.",
            target_owner="Example Demo Co. IT",
            authorized_by="Demo Operator",
            reference="DEMO-DATA-ONLY",
            window_start=now - timedelta(days=1),
            window_end=now + timedelta(days=30),
            notes="Synthetic authorization record for demo data; not a real engagement.",
        ),
        scope=ScopeDefinition(
            schemes=["https"],
            hosts=[DEMO_HOST],
            ports=[443],
            path_prefixes=["/"],
        ),
        scan_policy=ScanPolicy(allowed_modules=[ScanModule.WEB_APP, ScanModule.ATTACK_SURFACE]),
        labels=["demo"],
        notes="Synthetic demo project. Delete freely; nothing here reflects a real system.",
    )


def _demo_assets(project_id: str) -> list[Asset]:
    return [
        Asset(
            asset_id=new_id("asset"),
            project_id=project_id,
            asset_type=AssetType.HOSTNAME,
            locator=DEMO_HOST,
            scope_status=ScopeStatus.IN_SCOPE,
            confidence=Confidence.CONFIRMED,
            criticality="high",
        ),
        Asset(
            asset_id=new_id("asset"),
            project_id=project_id,
            asset_type=AssetType.PORT,
            locator=f"{DEMO_HOST}:443",
            scope_status=ScopeStatus.IN_SCOPE,
            confidence=Confidence.CONFIRMED,
        ),
    ]


def _demo_scan(project_id: str, now: datetime, module: ScanModule) -> ScanJob:
    return ScanJob(
        scan_id=new_id("scan"),
        project_id=project_id,
        module=module,
        targets=[f"https://{DEMO_HOST}/"],
        state=ScanState.COMPLETED,
        queued_at=now - timedelta(minutes=10),
        started_at=now - timedelta(minutes=9),
        finished_at=now - timedelta(minutes=5),
    )


def _demo_findings(project_id: str, scan_id: str) -> list[Finding]:
    common: dict[str, Any] = {
        "project_id": project_id,
        "scan_id": scan_id,
        "sources": [FindingSource(tool="demo-data-generator", rule_id="DEMO")],
    }
    return [
        Finding(
            finding_id=new_id("finding"),
            rule_id="WEB-HDR-002",
            title="Missing Content-Security-Policy header",
            severity=Severity.MEDIUM,
            confidence=Confidence.CONFIRMED,
            url=f"https://{DEMO_HOST}/",
            summary="The response did not include a Content-Security-Policy header.",
            technical_detail="Synthetic demo evidence — no real response was captured.",
            remediation="Add a Content-Security-Policy header appropriate to the application.",
            cwe_ids=[693],
            mappings=[
                StandardMapping(
                    catalog="owasp_top10",
                    catalog_version="2025",
                    entry_id="A05",
                    title="Security Misconfiguration",
                    rationale="Related category assigned by the rule catalog (not a 1:1 mapping)",
                )
            ],
            **common,
        ),
        Finding(
            finding_id=new_id("finding"),
            rule_id="WEB-COOKIE-002",
            title="Session cookie missing Secure flag",
            severity=Severity.HIGH,
            confidence=Confidence.PROBABLE,
            url=f"https://{DEMO_HOST}/login",
            summary="A session cookie was observed without the Secure attribute.",
            technical_detail="Synthetic demo evidence — illustrates how a cookie finding renders.",
            remediation="Set the Secure (and HttpOnly/SameSite) attributes on session cookies.",
            cwe_ids=[614],
            parameter="session_id",
            **common,
        ),
        Finding(
            finding_id=new_id("finding"),
            rule_id="WEB-TLS-004",
            title="TLS certificate nearing expiry",
            severity=Severity.LOW,
            confidence=Confidence.CONFIRMED,
            url=f"https://{DEMO_HOST}/",
            summary="The TLS certificate's validity window ends soon.",
            technical_detail="Synthetic demo evidence — illustrative only.",
            remediation="Renew the TLS certificate before expiry.",
            cwe_ids=[295],
            **common,
        ),
        Finding(
            finding_id=new_id("finding"),
            rule_id="WEB-INFO-002",
            title="Server banner discloses software version",
            severity=Severity.INFORMATIONAL,
            confidence=Confidence.CONFIRMED,
            url=f"https://{DEMO_HOST}/",
            summary="The Server header disclosed a specific software version.",
            technical_detail="Synthetic demo evidence — illustrative only.",
            remediation="Suppress or generalize the Server header's version detail.",
            cwe_ids=[200],
            **common,
        ),
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--data-dir",
        required=True,
        help="data directory to write the demo project into (created if missing)",
    )
    args = parser.parse_args(argv)

    try:
        repo = StorageRepository.open(RuntimeSettings(data_dir=args.data_dir))
    except StorageError as exc:
        print(f"error: could not open --data-dir {args.data_dir!r}: {exc.message}", file=sys.stderr)
        return 1
    try:
        now = datetime.now(UTC)
        project = repo.create_project(_demo_project(now))
        for asset in _demo_assets(project.project_id):
            repo.create_asset(asset)
        web_scan = repo.create_scan(_demo_scan(project.project_id, now, ScanModule.WEB_APP))
        for finding in _demo_findings(project.project_id, web_scan.scan_id):
            repo.create_finding(finding)
        print(f"Created demo project {project.project_id} ({project.name!r}) in {args.data_dir}")
        print("Nothing here was scanned; every record is synthetic. Safe to delete at any time.")
    finally:
        repo.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
